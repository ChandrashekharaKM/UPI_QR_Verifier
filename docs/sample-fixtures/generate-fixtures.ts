function rotatePng(src: PNG, degrees: 90 | 180 | 270): PNG {
  const newWidth = degrees === 90 || degrees === 270 ? src.height : src.width;
  const newHeight = degrees === 90 || degrees === 270 ? src.width : src.height;
  const dest = new PNG({ width: newWidth, height: newHeight });

  for (let y = 0; y < src.height; y++) {
    for (let x = 0; x < src.width; x++) {
      let destX = 0;
      let destY = 0;
      if (degrees === 90) {
        destX = src.height - 1 - y;
        destY = x;
      } else if (degrees === 180) {
        destX = src.width - 1 - x;
        destY = src.height - 1 - y;
      } else if (degrees === 270) {
        destX = y;
        destY = src.width - 1 - x;
      }
      const srcIdx = (y * src.width + x) * 4;
      const destIdx = (destY * newWidth + destX) * 4;
      dest.data[destIdx] = src.data[srcIdx] ?? 0;
      dest.data[destIdx + 1] = src.data[srcIdx + 1] ?? 0;
      dest.data[destIdx + 2] = src.data[srcIdx + 2] ?? 0;
      dest.data[destIdx + 3] = src.data[srcIdx + 3] ?? 255;
    }
  }
  return dest;
}

function applyBlurPng(src: PNG): PNG {
  const dest = new PNG({ width: src.width, height: src.height });
  const w = src.width;
  const h = src.height;

  for (let y = 1; y < h - 1; y++) {
    for (let x = 1; x < w - 1; x++) {
      let sum = 0;
      for (let dy = -1; dy <= 1; dy++) {
        for (let dx = -1; dx <= 1; dx++) {
          sum += src.data[((y + dy) * w + (x + dx)) * 4] ?? 255;
        }
      }
      const avg = Math.round(sum / 9);
      const idx = (y * w + x) * 4;
      dest.data[idx] = avg;
      dest.data[idx + 1] = avg;
      dest.data[idx + 2] = avg;
      dest.data[idx + 3] = 255;
    }
  }
  // Fill border
  for (let x = 0; x < w; x++) {
    const tIdx = x * 4;
    const bIdx = ((h - 1) * w + x) * 4;
    dest.data[tIdx] = 255; dest.data[tIdx + 1] = 255; dest.data[tIdx + 2] = 255; dest.data[tIdx + 3] = 255;
    dest.data[bIdx] = 255; dest.data[bIdx + 1] = 255; dest.data[bIdx + 2] = 255; dest.data[bIdx + 3] = 255;
  }
  for (let y = 0; y < h; y++) {
    const lIdx = y * w * 4;
    const rIdx = (y * w + (w - 1)) * 4;
    dest.data[lIdx] = 255; dest.data[lIdx + 1] = 255; dest.data[lIdx + 2] = 255; dest.data[lIdx + 3] = 255;
    dest.data[rIdx] = 255; dest.data[rIdx + 1] = 255; dest.data[rIdx + 2] = 255; dest.data[rIdx + 3] = 255;
  }

  return dest;
}

function applyLowContrastPng(src: PNG): PNG {
  const dest = new PNG({ width: src.width, height: src.height });
  for (let i = 0; i < src.data.length; i += 4) {
    const g = src.data[i] ?? 255;
    // Compress [0, 255] to [135, 175] (range 40, faded laminated look)
    const val = Math.round(135 + (g / 255) * 40);
    dest.data[i] = val;
    dest.data[i + 1] = val;
    dest.data[i + 2] = val;
    dest.data[i + 3] = 255;
  }
  return dest;
}

async function generateAllFixtures() {
  const outputDir = __dirname;
  console.log(`[Fixtures Generator] Output directory: ${outputDir}`);

  const manifest: Record<string, FixtureDefinition> = {};

  for (const fix of FIXTURES) {
    const filePath = path.join(outputDir, fix.filename);
    const size = fix.transformation === 'small' ? 120 : 400;

    const basePngBuf = await QRCode.toBuffer(fix.payload, {
      errorCorrectionLevel: 'H',
      margin: 2,
      width: size,
      color: {
        dark: '#000000',
        light: '#FFFFFF'
      }
    });

    if (fix.transformation === 'none' || fix.transformation === 'small' || !fix.transformation) {
      fs.writeFileSync(filePath, basePngBuf);
    } else {
      const origPng = PNG.sync.read(basePngBuf);
      let transformedPng: PNG = origPng;

      if (fix.transformation === 'rotate90') {
        transformedPng = rotatePng(origPng, 90);
      } else if (fix.transformation === 'rotate180') {
        transformedPng = rotatePng(origPng, 180);
      } else if (fix.transformation === 'rotate270') {
        transformedPng = rotatePng(origPng, 270);
      } else if (fix.transformation === 'blur') {
        transformedPng = applyBlurPng(origPng);
      } else if (fix.transformation === 'low_contrast') {
        transformedPng = applyLowContrastPng(origPng);
      }

      const outBuf = PNG.sync.write(transformedPng);
      fs.writeFileSync(filePath, outBuf);
    }

    manifest[fix.filename] = fix;
    console.log(`  ✓ Generated QR: ${fix.filename} [Expected: ${fix.expectedCategory}] (${fix.transformation ?? 'none'})`);
  }

  const manifestPath = path.join(outputDir, 'manifest.json');
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2), 'utf-8');
  console.log(`[Fixtures Generator] Manifest written to: ${manifestPath}`);
}

void generateAllFixtures();
