/**
 * Bilinear rotation by arbitrary angle degrees with clean white background margin.
 */
export function rotateBilinear(src: PNG, angleDegrees: number): PNG {
  const rad = (angleDegrees * Math.PI) / 180;
  const cos = Math.cos(rad);
  const sin = Math.sin(rad);

  const w = src.width;
  const h = src.height;

  const newW = Math.ceil(Math.abs(w * cos) + Math.abs(h * sin));
  const newH = Math.ceil(Math.abs(w * sin) + Math.abs(h * cos));

  const dest = new PNG({ width: newW, height: newH });
  dest.data.fill(255);

  const cxSrc = w / 2;
  const cySrc = h / 2;
  const cxDest = newW / 2;
  const cyDest = newH / 2;

  for (let y = 0; y < newH; y++) {
    const dy = y - cyDest;
    const destRow = y * newW;

    for (let x = 0; x < newW; x++) {
      const dx = x - cxDest;

      // Inverse mapping
      const sx = cxSrc + dx * cos + dy * sin;
      const sy = cySrc - dx * sin + dy * cos;

      if (sx >= 0 && sx < w - 1 && sy >= 0 && sy < h - 1) {
        const x0 = Math.floor(sx);
        const y0 = Math.floor(sy);
        const x1 = x0 + 1;
        const y1 = y0 + 1;

        const fx = sx - x0;
        const fy = sy - y0;

        const destIdx = (destRow + x) * 4;
        const row0 = y0 * w;
        const row1 = y1 * w;

        for (let c = 0; c < 3; c++) {
          const p00 = src.data[(row0 + x0) * 4 + c] ?? 255;
          const p10 = src.data[(row0 + x1) * 4 + c] ?? 255;
          const p01 = src.data[(row1 + x0) * 4 + c] ?? 255;
          const p11 = src.data[(row1 + x1) * 4 + c] ?? 255;

          const top = p00 * (1 - fx) + p10 * fx;
          const bottom = p01 * (1 - fx) + p11 * fx;
          dest.data[destIdx + c] = Math.round(top * (1 - fy) + bottom * fy);
        }
        dest.data[destIdx + 3] = 255;
      }
    }
  }

  return dest;
}

/**
 * 3x3 Gaussian defocus / camera motion blur simulation.
 */
export function applyBlur(src: PNG): PNG {
  const w = src.width;
  const h = src.height;
  const dest = new PNG({ width: w, height: h });

  // 3x3 Gaussian kernel
  const kernel = [
    1 / 16, 2 / 16, 1 / 16,
    2 / 16, 4 / 16, 2 / 16,
    1 / 16, 2 / 16, 1 / 16
  ];

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      let r = 0;
      let g = 0;
      let b = 0;

      for (let ky = -1; ky <= 1; ky++) {
        const py = Math.min(h - 1, Math.max(0, y + ky));
        for (let kx = -1; kx <= 1; kx++) {
          const px = Math.min(w - 1, Math.max(0, x + kx));
          const weight = kernel[(ky + 1) * 3 + (kx + 1)]!;
          const idx = (py * w + px) * 4;

          r += (src.data[idx] ?? 0) * weight;
          g += (src.data[idx + 1] ?? 0) * weight;
          b += (src.data[idx + 2] ?? 0) * weight;
        }
      }

      const destIdx = (y * w + x) * 4;
      dest.data[destIdx] = Math.round(r);
      dest.data[destIdx + 1] = Math.round(g);
      dest.data[destIdx + 2] = Math.round(b);
      dest.data[destIdx + 3] = src.data[destIdx + 3] ?? 255;
    }
  }

  return dest;
}

/**
 * 8x8 block DCT coefficient quantization simulating JPEG compression artifacts.
 */
export function applyJpegCompression(src: PNG): PNG {
  const w = src.width;
  const h = src.height;
  const dest = new PNG({ width: w, height: h });
  src.data.copy(dest.data);

  const C = (u: number) => (u === 0 ? 1 / Math.SQRT2 : 1);
  const Q = [
    16, 11, 10, 16, 24, 40, 51, 61,
    12, 12, 14, 19, 26, 58, 60, 55,
    14, 13, 16, 24, 40, 57, 69, 56,
    14, 17, 22, 29, 51, 87, 80, 62,
    18, 22, 37, 56, 68, 109, 103, 77,
    24, 35, 55, 64, 81, 104, 113, 92,
    49, 64, 78, 87, 103, 121, 120, 101,
    72, 92, 95, 98, 112, 100, 103, 99
  ];

  for (let by = 0; by < h; by += 8) {
    for (let bx = 0; bx < w; bx += 8) {
      const block = new Float64Array(64);
      for (let y = 0; y < 8; y++) {
        for (let x = 0; x < 8; x++) {
          const px = Math.min(w - 1, bx + x);
          const py = Math.min(h - 1, by + y);
          block[y * 8 + x] = dest.data[(py * w + px) * 4] ?? 0;
        }
      }

      // 2D DCT
      const coeffs = new Float64Array(64);
      for (let u = 0; u < 8; u++) {
        for (let v = 0; v < 8; v++) {
          let sum = 0;
          for (let x = 0; x < 8; x++) {
            for (let y = 0; y < 8; y++) {
              sum +=
                (block[y * 8 + x]! - 128) *
                Math.cos(((2 * x + 1) * u * Math.PI) / 16) *
                Math.cos(((2 * y + 1) * v * Math.PI) / 16);
            }
          }
          coeffs[u * 8 + v] = 0.25 * C(u) * C(v) * sum;
        }
      }

      // Quantization with moderate compression scale (1.2)
      for (let i = 0; i < 64; i++) {
        const qVal = Q[i]! * 1.2;
        coeffs[i] = Math.round(coeffs[i]! / qVal) * qVal;
      }

      // 2D Inverse DCT
      for (let x = 0; x < 8; x++) {
        for (let y = 0; y < 8; y++) {
          if (bx + x < w && by + y < h) {
            let sum = 0;
            for (let u = 0; u < 8; u++) {
              for (let v = 0; v < 8; v++) {
                sum +=
                  C(u) *
                  C(v) *
                  coeffs[u * 8 + v]! *
                  Math.cos(((2 * x + 1) * u * Math.PI) / 16) *
                  Math.cos(((2 * y + 1) * v * Math.PI) / 16);
              }
            }
            const val = Math.min(255, Math.max(0, Math.round(0.25 * sum + 128)));
            const idx = ((by + y) * w + (bx + x)) * 4;
            dest.data[idx] = val;
            dest.data[idx + 1] = val;
            dest.data[idx + 2] = val;
          }
        }
      }
    }
  }

  return dest;
}

/**
 * Compresses dynamic range [105, 175] simulating faded thermal receipt or midday counter glare.
 */
export function applyLowContrast(src: PNG, minVal = 105, maxVal = 175): PNG {
  const w = src.width;
  const h = src.height;
  const dest = new PNG({ width: w, height: h });

  for (let i = 0; i < src.data.length; i += 4) {
    const orig = src.data[i] ?? 0;
    const faded = Math.round(minVal + (orig / 255) * (maxVal - minVal));
    dest.data[i] = faded;
    dest.data[i + 1] = faded;
    dest.data[i + 2] = faded;
    dest.data[i + 3] = src.data[i + 3] ?? 255;
  }

  return dest;
}

/**
 * Simulates photographing a computer or phone LCD display:
 * - Subpixel horizontal raster lines (subtle periodic grid lines)
 * - Radial vignette from screen center
 * - Subtle corner glare gradient
 */
export function applyScreenSimulation(src: PNG): PNG {
  const w = src.width;
  const h = src.height;
  const dest = new PNG({ width: w, height: h });

  const cx = w / 2;
  const cy = h / 2;
  const maxDist = Math.sqrt(cx * cx + cy * cy);

  for (let y = 0; y < h; y++) {
    // Raster line attenuation (every 3rd scanline slightly darkened)
    const scanlineFactor = y % 3 === 0 ? 0.88 : 1.0;
    const dy = y - cy;

    for (let x = 0; x < w; x++) {
      const dx = x - cx;
      const dist = Math.sqrt(dx * dx + dy * dy);
      // Slight radial vignette
      const vignette = 1.0 - 0.12 * Math.pow(dist / maxDist, 2);

      // Subtle reflection gradient on top-left
      const glare = Math.max(0, 15 - Math.round((x + y) * 0.04));

      const idx = (y * w + x) * 4;
      const r = Math.min(255, Math.max(0, Math.round(((src.data[idx] ?? 0) * scanlineFactor * vignette) + glare)));
      const g = Math.min(255, Math.max(0, Math.round(((src.data[idx + 1] ?? 0) * scanlineFactor * vignette) + glare)));
      const b = Math.min(255, Math.max(0, Math.round(((src.data[idx + 2] ?? 0) * scanlineFactor * vignette) + glare)));

      dest.data[idx] = r;
      dest.data[idx + 1] = g;
      dest.data[idx + 2] = b;
      dest.data[idx + 3] = src.data[idx + 3] ?? 255;
    }
  }

  return dest;
}

/**
 * Generates all fixture image PNG files and writes manifest.json.
 */
export async function generateAllRealWorldFixtures(targetDir?: string): Promise<void> {
  const outputDir = targetDir ?? path.resolve(__dirname);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const manifestRecord: Record<string, RealWorldFixtureDef> = {};

  for (const item of REAL_WORLD_FIXTURES) {
    const rawQrBuffer = await QRCode.toBuffer(item.payload, {
      errorCorrectionLevel: 'M',
      margin: 4,
      width: 400
    });

    let png = PNG.sync.read(rawQrBuffer);

    switch (item.transformation) {
      case 'rotated_15':
        png = rotateBilinear(png, 15);
        break;
      case 'blurred':
        png = applyBlur(png);
        break;
      case 'jpeg_compressed':
        png = applyJpegCompression(png);
        break;
      case 'low_contrast':
        png = applyLowContrast(png);
        break;
      case 'screen_simulation':
        png = applyScreenSimulation(png);
        break;
      case 'none':
      default:
        // No degradation
        break;
    }

    const outputPath = path.join(outputDir, item.filename);
    fs.writeFileSync(outputPath, PNG.sync.write(png));
    manifestRecord[item.filename] = item;
  }

  const manifestPath = path.join(outputDir, 'manifest.json');
  fs.writeFileSync(manifestPath, JSON.stringify(manifestRecord, null, 2), 'utf-8');
  console.log(`Generated ${REAL_WORLD_FIXTURES.length} fixtures in ${outputDir}`);
}

// Auto-run if executed directly
if (process.argv[1] && process.argv[1].includes('generate-real-world-fixtures')) {
  generateAllRealWorldFixtures().catch((err) => {
    console.error('Error generating fixtures:', err);
    process.exit(1);
  });
}
